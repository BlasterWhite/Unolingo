"""Generates the adaptive launcher icon (docs/ui "Icône adaptative") as vector drawables.

- background: seiji teal with seigaiha waves in the bottom third;
- foreground: a 54 dp washi seal with Unolingo's "う" in sumi ink, vectorized from Klee One (no font in the icon);
- monochrome: the seal becomes a ring, the "う" stays filled (themed icons).

Usage (from the repo root): python tools/gen_icon.py
Requires fontTools and the bundled app/src/main/res/font/klee_one_semibold.ttf (see subset_fonts.py).
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
FONT = RES / "font/klee_one_semibold.ttf"

TEAL = "#FF006A66"
WAVE = "#FF29827E"  # onPrimary at 16 % over teal, as on the home banner
WASHI = "#FFFBF8F2"
SUMI = "#FF1C1B17"

SIZE = 108  # adaptive icon canvas, in dp; the visible safe zone is the central 66 dp circle
CENTER = SIZE / 2


def glyph_path(char: str, height: float) -> str:
    """SVG path of [char], scaled to [height] dp and centered on the canvas (y axis flipped)."""
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[ord(char)]
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    scale = height / (y_max - y_min)
    dx = CENTER - (x_min + x_max) / 2 * scale
    dy = CENTER + (y_min + y_max) / 2 * scale
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, dx, dy)))
    return pen.getCommands()


def circle(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0"


def vector(paths: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_icon.py: edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="{SIZE}dp"
    android:height="{SIZE}dp"
    android:viewportWidth="{SIZE}"
    android:viewportHeight="{SIZE}"
    tools:ignore="VectorPath">
{paths}</vector>
"""


def background() -> str:
    paths = [f'    <path android:fillColor="{TEAL}" android:pathData="M0,0h{SIZE}v{SIZE}h-{SIZE}z" />\n']
    radius = 7.0
    y = SIZE * 2 / 3
    row = 0
    # Row by row from the top: each row's fans are filled with teal first so they cover the row above.
    while y < SIZE + radius:
        centers = []
        x = 0.0 if row % 2 == 0 else radius
        while x < SIZE + radius:
            centers.append((x, y))
            x += 2 * radius
        fill = "".join(circle(cx, cy, radius) for cx, cy in centers)
        arcs = "".join(circle(cx, cy, radius * k) for cx, cy in centers for k in (0.88, 0.62, 0.36))
        paths.append(f'    <path android:fillColor="{TEAL}" android:pathData="{fill}" />\n')
        paths.append(
            f'    <path android:strokeColor="{WAVE}" android:strokeWidth="0.7" android:pathData="{arcs}" />\n'
        )
        y += radius / 2
        row += 1
    return vector("".join(paths))


def foreground() -> str:
    return vector(
        f'    <path android:fillColor="{WASHI}" android:pathData="{circle(CENTER, CENTER, 27)}" />\n'
        f'    <path android:fillColor="{SUMI}" android:pathData="{glyph_path("う", 30)}" />\n'
    )


def monochrome() -> str:
    return vector(
        f'    <path android:strokeColor="#FF000000" android:strokeWidth="3.5" '
        f'android:pathData="{circle(CENTER, CENTER, 25)}" />\n'
        f'    <path android:fillColor="#FF000000" android:pathData="{glyph_path("う", 28)}" />\n'
    )


for name, content in {
    "ic_launcher_background": background(),
    "ic_launcher_foreground": foreground(),
    "ic_launcher_monochrome": monochrome(),
}.items():
    target = RES / "drawable" / f"{name}.xml"
    target.write_text(content, encoding="utf-8", newline="\n")
    print(target, f"{len(content) // 1024} KB")
